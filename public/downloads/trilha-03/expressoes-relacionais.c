#include <stdio.h>

int main(void) {
    int a = 10;
    int b = 6;

    printf("a > b  : %d\n", a > b);
    printf("a < b  : %d\n", a < b);
    printf("a == b : %d\n", a == b);
    printf("a != b : %d\n", a != b);
    printf("a >= 10: %d\n", a >= 10);
    printf("b <= 6 : %d\n", b <= 6);
    return 0;
}
